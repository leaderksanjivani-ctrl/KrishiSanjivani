class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('krishi_lang') || 'en';
  }

  setLanguage(lang) {
    if (translations[lang]) {
      this.currentLang = lang;
      localStorage.setItem('krishi_lang', lang);
      this.updatePageText();
      document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
    }
  }

  t(key, replacements = {}) {
    let text = translations[this.currentLang]?.[key] || translations['en']?.[key] || key;
    for (const [rKey, val] of Object.entries(replacements)) {
      text = text.replace(new RegExp(`\\{${rKey}\\}`, 'g'), val);
    }
    return text;
  }

  updatePageText() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.innerText = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) {
        el.placeholder = this.t(key);
      }
    });
  }
}

window.i18n = new I18nManager();
document.addEventListener('DOMContentLoaded', () => window.i18n.updatePageText());
